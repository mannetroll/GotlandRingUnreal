"""Preserve the original mono PCM cycles as compiled data for the audio generator."""
from pathlib import Path
import wave,struct,hashlib,json
root=Path(__file__).resolve().parents[1]
source=root.parent/'GotlandRingUnity/Assets/Resources/Audio'
lines=['// Generated by Scripts/export_engine_audio.py from the owner-recorded MIT audio.','#pragma once','#include <cstdint>','namespace Ring {']
manifest=[]
for name in ['ImprezaLow','ImprezaMid','ImprezaHigh']:
    p=source/(name+'.wav')
    with wave.open(str(p)) as w:
        assert (w.getnchannels(),w.getsampwidth(),w.getframerate())==(1,2,44100)
        pcm=w.readframes(w.getnframes());samples=struct.unpack('<'+'h'*(len(pcm)//2),pcm)
    lines.append('inline constexpr int16_t '+name+'[]={'+','.join(map(str,samples))+'};')
    manifest.append(dict(file=p.name,sha256=hashlib.sha256(p.read_bytes()).hexdigest(),samples=len(samples),rate=44100,license='MIT; repository owner recording'))
lines.append('}')
(root/'Source/GotlandRingUnreal/EngineCycles.h').write_text('\n'.join(lines)+'\n')
(root/'Validation/engine_audio_sources.json').write_text(json.dumps(manifest,indent=2)+'\n')
